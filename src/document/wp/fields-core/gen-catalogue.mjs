// Writes catalogue.mjs, the Field dialog's data (docs/plans/word/plan.md §1.10, index-fields.md Field dialog), from fields.json in
// the planning folder: node src/document/wp/fields-core/gen-catalogue.mjs [planDir]. The output is committed, so no src module
// reads docs/plans. Each of the 77 dialog fields: [dialog name, code name, categories, description, syntax, general switches,
// properties, options, button, switches]. probe/dialogs/field.json wins over fields.json where they differ (DATE's options).
import fs from 'node:fs';
import path from 'node:path';

const planDir = process.argv[2] ?? 'A:/Programming Dumpster/DAF Writer/docs/plans/word';
const out = path.join(import.meta.dirname, 'catalogue.mjs');
const fields = JSON.parse(fs.readFileSync(path.join(planDir, 'fields.json'), 'utf8'));

export const CATEGORIES = ['Date and Time', 'Document Automation', 'Document Information', 'Equations and Formulas', 'Index and Tables',
  'Links and References', 'Mail Merge', 'Numbering', 'User Information'];

// The probe's Field dialog for DATE (probe/dialogs/field.json, state date): four options with their access keys.
const OVERRIDES = {
  DATE: {
    options: ['Use the &Hijri/Lunar calendar', 'Insert the date in &last used format from Insert tab', 'Use the &Saka Era calendar', '&Use the Um-al-Qura calendar'],
    switches: [{ switch: '\\u', meaning: 'Uses the Um-al-Qura calendar' }],
  },
};

/** One property line of fields.json → [kind, label, items?]: date, format lists, numeric, a list argument or a text box. */
function prop(p) {
  if (/^Date formats?:/.test(p)) return ['date', '&Date formats:'];
  if (/^Format: \(number formats and text formats\)/.test(p)) return ['both', 'Forma&t:'];
  if (/^Format: \(number formats\)/.test(p)) return ['number', 'Forma&t:'];
  if (/^Format: \(text formats\)/.test(p)) return ['text', 'Forma&t:'];
  if (/^Numeric format/.test(p)) return ['numeric', 'N&umeric format:'];
  let m = /^(.*?:)\s*\((.*)\)$/.exec(p);
  if (m) {
    const src = { 'bookmarks in the document': 'bookmarks', 'styles in the document': 'styles', 'AutoText entries': 'autotext' }[m[2]];
    if (src) return ['list', m[1], src];
    if (/\d+ /.test(m[2]) || /commands and macros/.test(m[2])) return ['box', m[1]];
    return ['list', m[1], m[2].split(', ')];
  }
  m = /^(.*?) box(?: and list)?/.exec(p);
  if (m) return ['box', `${m[1]}:`];
  return ['box', p];
}

const words = (s) => new Set(String(s).toLowerCase().match(/[a-z]{4,}/g) ?? []);

/** Field options → [label, switch index, takes a value]: in the switches' order when the counts match, else by shared words. */
function options(list, switches) {
  return list.map((label, i) => {
    let at = list.length === switches.length ? i : -1;
    if (at < 0) {
      const w = words(label);
      let best = 0;
      switches.forEach((s, k) => {
        const n = [...words(s.meaning)].filter((x) => w.has(x) || w.has(x.replace(/s$/, ''))).length;
        if (n > best) [best, at] = [n, k];
      });
    }
    return [label, at, label.trim().endsWith(':') ? 1 : 0];
  });
}

const rows = fields.filter((f) => f.dialogName).sort((a, b) => a.dialogName.localeCompare(b.dialogName, 'en')).map((f) => {
  const o = OVERRIDES[f.name] ?? {};
  const switches = [...f.switches, ...(o.switches ?? [])];
  const cats = f.category.map((c) => CATEGORIES.indexOf(c)).filter((i) => i >= 0);
  const dialog = f.dialog ?? { properties: [], options: [], button: null };
  return [f.dialogName, f.name, cats, f.description, f.syntax, f.generalSwitches.map((s) => s[1]).join(''),
    dialog.properties.map(prop), options(o.options ?? dialog.options, switches), dialog.button,
    switches.map((s) => [s.switch, s.meaning])];
});

const body = `// Generated by gen-catalogue.mjs from fields.json (docs/plans/word). Do not edit by hand.
/** The Field dialog's categories, in the Categories list's order after (All). */
export const CATEGORIES = ${JSON.stringify(CATEGORIES)};
/** The 77 fields of the Field names list: [dialog name, code name, category indexes, description, syntax, general switches ('*#@!'),
 * properties [kind, label, items?], options [label, switch index, takes a value], button, switches [switch, meaning]]. */
export const FIELDS = ${JSON.stringify(rows)};
`;
fs.writeFileSync(out, body);
console.log(`${out}: ${rows.length} fields, ${(body.length / 1024).toFixed(1)} KB`);
