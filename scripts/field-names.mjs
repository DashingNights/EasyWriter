// Writes src/document/fields/names.mjs, every field name Word knows, from the planning folder's fields.json
// (docs/plans/word/plan.md §1.1: no src module imports docs/plans, which is gitignored).
//   node scripts/field-names.mjs [planDir]
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const planDir = process.argv[2] ?? 'A:/Programming Dumpster/DAF Writer/docs/plans/word';
const names = JSON.parse(readFileSync(join(planDir, 'fields.json'), 'utf8')).map((f) => f.name);
const lines = [];
let line = ' ';
for (const n of names.map((x) => `'${x}',`)) {
  if (line.length + n.length + 1 > 130) {
    lines.push(line);
    line = ' ';
  }
  line += ` ${n}`;
}
lines.push(line);
const out = `// Generated by scripts/field-names.mjs from fields.json. Do not edit by hand.

/** Every field name Word knows. A first word outside this list and the registered types is a bookmark name: Word's implicit REF. */
export const FIELD_NAMES = Object.freeze([
${lines.join('\n')}
]);
`;
writeFileSync(new URL('../src/document/fields/names.mjs', import.meta.url), out);
console.log(`${names.length} field names`);
