// Rebuilds the metafile reader's WebAssembly (src/vendor/wordcraft-metafile, README.md) with cargo and wasm-bindgen, so that
// npm run build itself needs no Rust toolchain: it bundles the committed glue and bytes this writes.
//   node scripts/build-metafile-wasm.mjs
// Needs the toolchain engine/rust-toolchain.toml pins, with its wasm32-unknown-unknown target, and wasm-bindgen-cli at the version
// binding/Cargo.toml pins (0.2.129).
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'src', 'vendor', 'wordcraft-metafile');
// Cargo's output stays out of the repository (and out of esbuild's and the graph's way).
const target = path.join(os.tmpdir(), 'easywriter-wcmeta-target');
const out = fs.mkdtempSync(path.join(os.tmpdir(), 'easywriter-wcmeta-'));
const run = (cmd, args, cwd) => execFileSync(cmd, args, { cwd, stdio: 'inherit', env: { ...process.env, CARGO_TARGET_DIR: target } });

try {
  // Run from engine/, so rustup takes the toolchain its rust-toolchain.toml pins.
  run('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '--manifest-path', path.join(dir, 'binding', 'Cargo.toml')], path.join(root, 'engine'));
  // The bundler target's wcmeta_bg.js is the glue alone (no import.meta, no fetch): index.mjs instantiates the bytes itself.
  // It is kept as .mjs, so Node reads it as the ES module it is.
  run('wasm-bindgen', ['--target', 'bundler', '--no-typescript', '--out-dir', out, path.join(target, 'wasm32-unknown-unknown', 'release', 'wcmeta.wasm')], dir);
  const wasm = fs.readFileSync(path.join(out, 'wcmeta_bg.wasm'));
  fs.copyFileSync(path.join(out, 'wcmeta_bg.js'), path.join(dir, 'wcmeta_bg.mjs'));
  fs.writeFileSync(path.join(dir, 'wcmeta_bg.wasm'), wasm);
  fs.writeFileSync(path.join(dir, 'wasm-bytes.mjs'), `// Generated by scripts/build-metafile-wasm.mjs from wcmeta_bg.wasm: the module's bytes as base64.\nexport default '${wasm.toString('base64')}';\n`);
  console.log(`wcmeta_bg.wasm: ${wasm.length} bytes`);
} finally {
  fs.rmSync(out, { recursive: true, force: true });
}
